// Regenerates sw.js: the cache name is a hash of the shipped files and the precache list is every file of the app.
// Run it (npm run build) before publishing whenever a file under src/, styles/ or assets/ changes.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SHIP = ['index.html', 'manifest.webmanifest', 'icon-180.png', 'icon-192.png', 'icon-512.png'];
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const files = [...SHIP, ...['src', 'styles', 'assets'].flatMap(d => walk(path.join(ROOT, d)).map(f => path.relative(ROOT, f).split(path.sep).join('/')))].sort();
const hash = crypto.createHash('sha1');
for (const f of files) hash.update(fs.readFileSync(path.join(ROOT, f)));

const sw = `// GENERATED by scripts/build-sw.mjs — do not edit by hand.
// Precaches the whole app so it opens offline. Other GETs are network-first with a cache fallback,
// so a new deploy is picked up on the next online visit.
const CACHE = 'ultra-${hash.digest('hex').slice(0, 8)}';
const ASSETS = ${JSON.stringify(['./', ...files], null, 2)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS))); self.skipWaiting(); });
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(k => Promise.all(k.filter(x => x !== CACHE).map(x => caches.delete(x)))));
  self.clients.claim();
});
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  e.respondWith(fetch(e.request).then(r => { if (r.ok) { const cp = r.clone(); caches.open(CACHE).then(c => c.put(e.request, cp)); } return r; })
    .catch(() => caches.match(e.request).then(m => m || caches.match('index.html'))));
});
`;
fs.writeFileSync(path.join(ROOT, 'sw.js'), sw);
console.log(`sw.js: ${files.length + 1} archivos en el precaché`);
